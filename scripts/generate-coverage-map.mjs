import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

// Run with the pinned geoBoundaries GeoJSON as the first argument (see README).
const input = process.argv[2]
if (!input) throw new Error('Provide the geoBoundaries POL ADM1 GeoJSON file.')

const data = JSON.parse(readFileSync(input, 'utf8'))
const region = data.features.find((feature) => feature.properties.shapeISO === 'PL-PM')
if (!region || region.geometry.type !== 'Polygon') {
  throw new Error('Expected the PL-PM Polygon in the source dataset.')
}

const points = region.geometry.coordinates.flat()
const west = Math.min(...points.map(([longitude]) => longitude))
const east = Math.max(...points.map(([longitude]) => longitude))
const south = Math.min(...points.map(([, latitude]) => latitude))
const north = Math.max(...points.map(([, latitude]) => latitude))
const longitudeScale = Math.cos(((south + north) / 2) * Math.PI / 180)
const scale = Math.min(536 / ((east - west) * longitudeScale), 416 / (north - south))
const offsetX = (600 - (east - west) * longitudeScale * scale) / 2
const offsetY = (480 - (north - south) * scale) / 2
const project = ([longitude, latitude]) => [
  Number((offsetX + (longitude - west) * longitudeScale * scale).toFixed(2)),
  Number((offsetY + (north - latitude) * scale).toFixed(2)),
]
const outlinePath = region.geometry.coordinates.map((ring) => (
  ring.map((point, index) => `${index === 0 ? 'M' : 'L'}${project(point).join(',')}`).join('') + 'Z'
)).join('')

mkdirSync('public/maps', { recursive: true })
writeFileSync('public/maps/pomorskie.geojson', JSON.stringify({
  type: 'FeatureCollection',
  source: 'geoBoundaries POL-ADM1-17162690 / OpenStreetMap contributors / Wambacher',
  license: 'ODbL-1.0: https://opendatacommons.org/licenses/odbl/1-0/',
  features: [region],
}) + '\n')
writeFileSync('src/config/pomorskieOutline.ts', `// Generated by scripts/generate-coverage-map.mjs; do not edit the outline manually.
// geoBoundaries / OpenStreetMap contributors / Wambacher, ODbL-1.0. See README.
export const pomorskieOutline = {
  viewBox: '0 0 600 480',
  outlinePath: '${outlinePath}',
  gdansk: { x: ${project([18.6540233, 54.3482907])[0]}, y: ${project([18.6540233, 54.3482907])[1]} },
}
`)
console.log('Generated Pomeranian outline; Gdańsk SVG coordinates:', project([18.6540233, 54.3482907]))
